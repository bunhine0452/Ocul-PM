//! 확인 해시 — 프론트매터 `verified_hash` 의 값을 만드는 한 함수
//! ({#reviewed-hash}, 2026-09-15). `mod.rs` 는 파일 크기 래칫에 걸려 있어 형제
//! 파일로 두고 `mod.rs` 가 `pub use` 로 다시 내보낸다.

/// 사람의 「확인」이 묶이는 본문 해시 — 프론트매터 `verified_hash` 의 값.
///
/// 입력은 [`super::parse_frontmatter_and_body`] 가 돌려준 **디스크 그대로의 본문**
/// (마스킹 전, 캐시 투영이 아니라 SSOT)이다. 정규화는 **꼬리 공백 제거 하나뿐**
/// — 편집기가 마지막 개행을 붙이거나 떼는 것은 내용 변경이 아니어서다. 그
/// 밖의 바이트는 전부 뜻이 있다고 본다: 앞 공백·줄 끝 공백·CRLF 까지 그대로
/// 해시에 들어간다 (정규화가 넓을수록 "바뀌었는데 같다" 가 늘어난다).
///
/// 형식은 `blake3:<64-hex>` — 알고리즘을 값에 적어 두어야 나중에 바꿔도 옛
/// 값을 읽고 "모르는 알고리즘 → 오래됨" 으로 떨어뜨릴 수 있다.
///
/// `schema_version` 은 1 그대로다: 파서가 키를 이름으로 골라 읽어 모르는 키를
/// 버리지 않고(`coerce_frontmatter` 는 `deny_unknown_fields` 가 아니다), 버전
/// 값은 읽기만 하고 비교하지 않으므로 이 키가 있는 일지를 옛 앱·플러그인이
/// 거부하지 않는다. 옛 앱이 프론트매터를 다시 쓰면 이 줄이 빠질 수는 있고,
/// 그 결과는 「해시 없는 확인」= 옛 일지와 같이 유효로 남는다 (거짓 「다시
/// 검토」는 생기지 않는다). `agent.session`(037) 이 같은 방식으로 더해졌다.
pub fn verified_body_hash(body: &str) -> String {
    format!(
        "blake3:{}",
        blake3::hash(body.trim_end().as_bytes()).to_hex()
    )
}
